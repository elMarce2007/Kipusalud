CREATE SCHEMA IF NOT EXISTS kipusalud_inventory;

CREATE TABLE kipusalud_inventory.ingresos_mercaderia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmacia_id BIGINT NOT NULL,
    clave_idempotencia VARCHAR(100) NOT NULL,
    huella_solicitud VARCHAR(64) NOT NULL,
    referencia_documento VARCHAR(120),
    creado_por VARCHAR(150) NOT NULL,
    creado_en TIMESTAMP NOT NULL,
    CONSTRAINT uq_ingreso_farmacia_idempotencia UNIQUE (farmacia_id, clave_idempotencia)
);

CREATE TABLE kipusalud_inventory.lotes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmacia_id BIGINT NOT NULL,
    producto_id BIGINT NOT NULL,
    codigo_lote VARCHAR(100) NOT NULL,
    fecha_vencimiento DATE,
    cantidad_inicial INTEGER NOT NULL,
    cantidad_disponible INTEGER NOT NULL,
    verificado BOOLEAN NOT NULL,
    creado_en TIMESTAMP NOT NULL,
    CONSTRAINT ck_lote_cantidad_inicial CHECK (cantidad_inicial >= 0),
    CONSTRAINT ck_lote_cantidad_disponible CHECK (
        cantidad_disponible >= 0 AND cantidad_disponible <= cantidad_inicial
    ),
    CONSTRAINT uq_lote_farmacia_producto_codigo UNIQUE (farmacia_id, producto_id, codigo_lote)
);

CREATE TABLE kipusalud_inventory.movimientos_inventario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmacia_id BIGINT NOT NULL,
    producto_id BIGINT NOT NULL,
    lote_id BIGINT,
    ingreso_id BIGINT,
    tipo VARCHAR(30) NOT NULL,
    cantidad INTEGER NOT NULL,
    clave_idempotencia VARCHAR(100) NOT NULL,
    actor VARCHAR(150) NOT NULL,
    creado_en TIMESTAMP NOT NULL,
    CONSTRAINT fk_movimiento_lote FOREIGN KEY (lote_id)
        REFERENCES kipusalud_inventory.lotes(id),
    CONSTRAINT fk_movimiento_ingreso FOREIGN KEY (ingreso_id)
        REFERENCES kipusalud_inventory.ingresos_mercaderia(id),
    CONSTRAINT uq_movimiento_farmacia_idempotencia
        UNIQUE (farmacia_id, clave_idempotencia)
);

CREATE INDEX idx_lotes_farmacia_producto_vencimiento
    ON kipusalud_inventory.lotes(farmacia_id, producto_id, fecha_vencimiento);
CREATE INDEX idx_lotes_farmacia_vencimiento
    ON kipusalud_inventory.lotes(farmacia_id, fecha_vencimiento)
    WHERE verificado AND cantidad_disponible > 0;
CREATE INDEX idx_movimientos_farmacia_producto_fecha
    ON kipusalud_inventory.movimientos_inventario(farmacia_id, producto_id, creado_en DESC);

