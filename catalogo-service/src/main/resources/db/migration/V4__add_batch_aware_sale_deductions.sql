CREATE TABLE kipusalud_inventory.salidas_venta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmacia_id BIGINT NOT NULL,
    clave_idempotencia VARCHAR(100) NOT NULL,
    huella_solicitud VARCHAR(64) NOT NULL,
    creado_por VARCHAR(150) NOT NULL,
    creado_en TIMESTAMP NOT NULL,
    CONSTRAINT uq_salida_venta_farmacia_idempotencia UNIQUE (farmacia_id, clave_idempotencia)
);

ALTER TABLE kipusalud_inventory.movimientos_inventario
    ADD COLUMN salida_id BIGINT;

ALTER TABLE kipusalud_inventory.movimientos_inventario
    ADD CONSTRAINT fk_movimiento_salida
    FOREIGN KEY (salida_id) REFERENCES kipusalud_inventory.salidas_venta(id);

CREATE INDEX idx_movimientos_farmacia_salida
    ON kipusalud_inventory.movimientos_inventario(farmacia_id, salida_id, id);
