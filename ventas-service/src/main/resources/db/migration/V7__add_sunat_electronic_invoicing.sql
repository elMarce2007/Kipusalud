CREATE TABLE sunat_configuraciones (
    farmacia_id BIGINT PRIMARY KEY,
    ruc VARCHAR(11) NOT NULL,
    razon_social VARCHAR(150) NOT NULL,
    direccion_fiscal VARCHAR(255) NOT NULL,
    ubigeo VARCHAR(6) NOT NULL,
    departamento VARCHAR(100) NOT NULL,
    provincia VARCHAR(100) NOT NULL,
    distrito VARCHAR(100) NOT NULL,
    serie_factura VARCHAR(4) NOT NULL,
    siguiente_numero BIGINT NOT NULL DEFAULT 1,
    sol_usuario_cifrado BYTEA NOT NULL,
    sol_clave_cifrada BYTEA NOT NULL,
    certificado_cifrado BYTEA NOT NULL,
    certificado_clave_cifrada BYTEA NOT NULL
);

CREATE TABLE comprobantes_electronicos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmacia_id BIGINT NOT NULL,
    venta_id BIGINT NOT NULL,
    tipo_comprobante VARCHAR(2) NOT NULL DEFAULT '01',
    serie VARCHAR(4) NOT NULL,
    numero VARCHAR(8) NOT NULL,
    estado VARCHAR(30) NOT NULL,
    nombre_archivo VARCHAR(80) NOT NULL,
    xml_firmado TEXT NOT NULL,
    cdr_zip BYTEA,
    codigo_respuesta VARCHAR(20),
    descripcion_respuesta VARCHAR(1000),
    fecha_creacion TIMESTAMP NOT NULL,
    fecha_respuesta TIMESTAMP,
    CONSTRAINT fk_comprobante_venta
        FOREIGN KEY (venta_id) REFERENCES ventas(id),
    CONSTRAINT uk_comprobante_venta UNIQUE (farmacia_id, venta_id),
    CONSTRAINT uk_comprobante_numero UNIQUE (farmacia_id, tipo_comprobante, serie, numero)
);

CREATE INDEX idx_comprobante_farmacia_estado
    ON comprobantes_electronicos (farmacia_id, estado);
