CREATE TABLE informacion_clinica_clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmacia_id BIGINT NOT NULL,
    cliente_id BIGINT NOT NULL,
    diagnosticos TEXT,
    tratamientos TEXT,
    alergias TEXT,
    medicamentos TEXT,
    CONSTRAINT uq_informacion_clinica_cliente UNIQUE (farmacia_id, cliente_id),
    CONSTRAINT fk_informacion_clinica_cliente
        FOREIGN KEY (cliente_id) REFERENCES clientes(id)
);

CREATE TABLE auditoria_acceso_clinico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmacia_id BIGINT NOT NULL,
    cliente_id BIGINT NOT NULL,
    usuario VARCHAR(50) NOT NULL,
    accion VARCHAR(20) NOT NULL,
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_auditoria_clinica_farmacia_fecha
    ON auditoria_acceso_clinico(farmacia_id, creado_en DESC);
